    void QueryBin() {
        binStale = false;
        try {
            SHQUERYRB q = new SHQUERYRB(); q.cbSize = (uint)Marshal.SizeOf(typeof(SHQUERYRB));
            if (Native.SHQueryRecycleBin(null, ref q) == 0) binItems = q.NumItems;
        } catch { }
    }
    static void OpenBin() { try { Process.Start("explorer.exe", "shell:RecycleBinFolder"); } catch { } }
    static void RunSta(ThreadStart work) {
        Thread t = new Thread(work);
        t.SetApartmentState(ApartmentState.STA); t.IsBackground = true; t.Start();
    }
    void EmptyBin() {
        // Windows shows its usual "are you sure" box, then empties the bin.
        RunSta(delegate { try { Native.SHEmptyRecycleBin(IntPtr.Zero, null, 0); } catch { } binStale = true; });
    }
    void RecycleFiles(string[] files) {
        string from = string.Join("\0", files) + "\0";
        RunSta(delegate {
            SHFILEOP op = new SHFILEOP();
            op.wFunc = 3;                // FO_DELETE
            op.pFrom = from;
            op.fFlags = 0x40 | 0x4000;   // FOF_ALLOWUNDO (goes to the bin) | FOF_WANTNUKEWARNING
            try { Native.SHFileOperation(ref op); } catch { }
            binStale = true;
        });
    }
