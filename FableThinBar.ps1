    // Keep the hidden-icons popup centred right above our arrow (Windows puts it above its own, hidden taskbar).
    void PlaceOverflow(IntPtr h) {
        if (h == IntPtr.Zero || trayArrowR.IsEmpty) return;
        RECT r; if (!Native.GetWindowRect(h, out r)) return;
        int w = r.Right - r.Left, ht = r.Bottom - r.Top;
        if (w <= 0 || ht <= 0) return;
        Rectangle a = RectangleToScreen(trayArrowR);
        Rectangle scr = Screen.FromRectangle(a).Bounds;
        int x = a.Left + a.Width / 2 - w / 2;
        x = Math.Max(scr.Left + 4, Math.Min(x, scr.Right - w - 4));
        int y = Bounds.Top - ht - (int)(6 * scale);
        if (Math.Abs(r.Left - x) > 1 || Math.Abs(r.Top - y) > 1)
            Native.SetWindowPos(h, IntPtr.Zero, x, y, 0, 0, 0x0001 | 0x0004 | 0x0010);   // NOSIZE | NOZORDER | NOACTIVATE
    }
