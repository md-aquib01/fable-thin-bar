// Windows 11 style popup menu: dark, rounded, hover highlight, icon + label.
class PopMenu : Form {
    static readonly Color BG = Color.FromArgb(44, 44, 44);
    static readonly Color HOV = Color.FromArgb(64, 64, 64);
    static readonly Color BORDER = Color.FromArgb(68, 68, 68);
    static readonly Color FG = Color.FromArgb(242, 242, 242);
    static readonly Color DIM = Color.FromArgb(125, 125, 125);

    float sc; Font font, icons;
    int pad, ih, sepH, iconCol, rpad;
    List<PopItem> items = new List<PopItem>();
    List<Rectangle> rects = new List<Rectangle>();
    int hover = -1;

    public PopMenu(float scale) {
        sc = scale;
        DoubleBuffered = true;
        FormBorderStyle = FormBorderStyle.None;
        ShowInTaskbar = false;
        StartPosition = FormStartPosition.Manual;
        TopMost = true;
        KeyPreview = true;
        BackColor = BG;
        font = new Font("Segoe UI", 9.5f);
        icons = new Font("Segoe MDL2 Assets", 10f);
        pad = (int)(4 * sc); ih = (int)(34 * sc); sepH = (int)(9 * sc);
        iconCol = (int)(38 * sc); rpad = (int)(16 * sc);
    }

    protected override CreateParams CreateParams {
        get { CreateParams cp = base.CreateParams; cp.ExStyle |= 0x80; cp.ClassStyle |= 0x20000; return cp; } // TOOLWINDOW, drop shadow
    }
    protected override void OnHandleCreated(EventArgs e) { base.OnHandleCreated(e); Ui.Corners(Handle); }
    protected override void OnDeactivate(EventArgs e) { base.OnDeactivate(e); if (Visible) Hide(); }

    public void Open(List<PopItem> list, Rectangle anchor, int barTop) {
        items = list; rects.Clear();
        int tw = 0;
        foreach (PopItem it in items)
            if (!it.Sep) tw = Math.Max(tw, TextRenderer.MeasureText(it.Text, font, new Size(int.MaxValue, ih), TextFormatFlags.NoPadding | TextFormatFlags.NoPrefix).Width);
        int W = Math.Max((int)(170 * sc), 2 * pad + iconCol + tw + rpad);
        int y = pad;
        foreach (PopItem it in items) { int h = it.Sep ? sepH : ih; rects.Add(new Rectangle(pad, y, W - 2 * pad, h)); y += h; }
        int H = y + pad;
        Rectangle scr = Screen.FromRectangle(anchor).Bounds;
        int x = anchor.Left + anchor.Width / 2 - W / 2;
        x = Math.Max(scr.Left + 8, Math.Min(x, scr.Right - W - 8));
        Bounds = new Rectangle(x, Math.Max(scr.Top + 8, barTop - H - (int)(6 * sc)), W, H);
        hover = -1;
        Show();
        Native.SetForegroundWindow(Handle);
        Invalidate();
    }

    int HitIndex(Point p) {
        for (int i = 0; i < rects.Count && i < items.Count; i++) if (!items[i].Sep && rects[i].Contains(p)) return i;
        return -1;
    }
    void Run(int i) { Action a = items[i].A; Hide(); if (a != null) a(); }
    void Step(int d) {
        int n = items.Count; if (n == 0) return;
        int i = (hover < 0 && d < 0) ? 0 : hover;
        for (int k = 0; k < n; k++) {
            i = (i + d + n) % n;
            if (!items[i].Sep && !items[i].Disabled) { hover = i; Invalidate(); return; }
        }
    }

    protected override void OnPaint(PaintEventArgs e) {
        Graphics g = e.Graphics;
        g.Clear(BG);
        using (Pen bp = new Pen(BORDER)) g.DrawRectangle(bp, 0, 0, ClientSize.Width - 1, ClientSize.Height - 1);
        TextFormatFlags tf = TextFormatFlags.NoPadding | TextFormatFlags.VerticalCenter | TextFormatFlags.Left | TextFormatFlags.EndEllipsis | TextFormatFlags.NoPrefix;
        for (int i = 0; i < rects.Count && i < items.Count; i++) {
            PopItem it = items[i]; Rectangle r = rects[i];
            if (it.Sep) {
                using (Pen sp = new Pen(BORDER)) g.DrawLine(sp, r.X + (int)(8 * sc), r.Y + r.Height / 2, r.Right - (int)(8 * sc), r.Y + r.Height / 2);
                continue;
            }
            if (i == hover && !it.Disabled) {
                g.SmoothingMode = SmoothingMode.AntiAlias;
                using (GraphicsPath gp = Ui.Round(r, (int)(5 * sc))) using (SolidBrush hb = new SolidBrush(HOV)) g.FillPath(hb, gp);
                g.SmoothingMode = SmoothingMode.Default;
            }
            Color fc = it.Disabled ? DIM : FG;
            if (it.Icon != null)
                TextRenderer.DrawText(g, it.Icon, icons, new Rectangle(r.X, r.Y, iconCol, r.Height), fc, TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.NoPadding);
            TextRenderer.DrawText(g, it.Text, font, new Rectangle(r.X + iconCol, r.Y, r.Width - iconCol - (int)(8 * sc), r.Height), fc, tf);
        }
    }

    protected override void OnMouseMove(MouseEventArgs e) {
        int hi = HitIndex(e.Location);
        if (hi != hover) { hover = hi; Invalidate(); }
        base.OnMouseMove(e);
    }
    protected override void OnMouseLeave(EventArgs e) { if (hover != -1) { hover = -1; Invalidate(); } base.OnMouseLeave(e); }
    protected override void OnMouseUp(MouseEventArgs e) {
        if (e.Button == MouseButtons.Left) {
            int hi = HitIndex(e.Location);
            if (hi >= 0 && !items[hi].Disabled) Run(hi);
        }
        base.OnMouseUp(e);
    }
    protected override void OnKeyDown(KeyEventArgs e) {
        if (e.KeyCode == Keys.Escape) Hide();
        else if (e.KeyCode == Keys.Down) Step(1);
        else if (e.KeyCode == Keys.Up) Step(-1);
        else if (e.KeyCode == Keys.Enter && hover >= 0 && !items[hover].Disabled) Run(hover);
        base.OnKeyDown(e);
    }
}


