    // ---------- layout (monospace, so wrapping is exact) ----------
    static List<string> Wrap(string text, int cols) {
        List<string> lines = new List<string>();
        foreach (string para in (text ?? "").Replace("\r\n", "\n").Split('\n')) {
            if (para.Length == 0) { lines.Add(""); continue; }
            int pos = 0;
            while (pos < para.Length) {
                if (para.Length - pos <= cols) { lines.Add(para.Substring(pos)); break; }
                int brk = para.LastIndexOf(' ', pos + cols, cols + 1);   // last space that still fits
                if (brk <= pos) { lines.Add(para.Substring(pos, cols)); pos += cols; }   // one very long word: break it
                else { lines.Add(para.Substring(pos, brk - pos)); pos = brk + 1; }
            }
        }
        if (lines.Count == 0) lines.Add("");
        return lines;
    }
    int ColsFor(int tx) { return Math.Max(4, (int)Math.Floor((Wn - tx - 10 * sc) / cw)); }

    void LayoutBody() {
        blks.Clear();
        int line = 0;
        for (int i = 0; i < D.Tasks.Count; i++) {
            TaskItem t = D.Tasks[i];
            Blk b = new Blk();
            b.Tx = textX + t.Level * indentPx;
            b.Cols = ColsFor(b.Tx);
            b.Lines = Wrap(t.Text, b.Cols);
            b.Count = (edKind == 1 && edIndex == i) ? Math.Max(1, editLines) : b.Lines.Count;
            b.Start = line; line += b.Count;
            blks.Add(b);
        }
        addStart = line;
        addTx = textX + newLevel * indentPx;
        totalLines = line + ((edKind == 2) ? Math.Max(1, editLines) : 1);
    }
    void ClampScroll(int vis) {
        int maxScroll = Math.Max(0, totalLines - vis);
        if (scroll > maxScroll) scroll = maxScroll;
        if (scroll < 0) scroll = 0;
    }

