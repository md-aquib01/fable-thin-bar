            if (old != IntPtr.Zero) Native.SelectObject(mem, old);
            if (hb != IntPtr.Zero) Native.DeleteObject(hb);
            Native.DeleteDC(mem);
            Native.ReleaseDC(IntPtr.Zero, scr);
        }
    }
