            File.WriteAllLines(settingsFile, new string[] { "style=" + style, "stats=" + (showStats ? 1 : 0) });
        } catch { }
    }
    // Uses Windows' (undocumented) accent policy: blur behind the bar, or a fully clear bar.
    static void SetAccent(IntPtr h, int state, int color) {
        ACCENT a = new ACCENT(); a.State = state; a.Flags = (state >= 2) ? 2 : 0; a.GradientColor = color; a.AnimationId = 0;
        int size = Marshal.SizeOf(typeof(ACCENT));
        IntPtr ptr = Marshal.AllocHGlobal(size);
        try {
            Marshal.StructureToPtr(a, ptr, false);
            WCAD d = new WCAD(); d.Attribute = 19; d.Data = ptr; d.SizeOfData = size;   // WCA_ACCENT_POLICY
            Native.SetWindowCompositionAttribute(h, ref d);
        } finally { Marshal.FreeHGlobal(ptr); }
    }
    void ApplyStyle() {
        try {
            if (style == 1) SetAccent(Handle, 3, unchecked((int)0x99141414));   // blur + dark tint (ABGR)
            else if (style == 2) SetAccent(Handle, 2, 0x01000000);              // clear
            else SetAccent(Handle, 0, 0);                                       // solid
            BackColor = (style == 0) ? BG : Color.Black;
        } catch (Exception ex) { Log.Write("style: " + ex); }
        Invalidate();
    }

