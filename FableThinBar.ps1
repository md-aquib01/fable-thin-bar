        if (rest.Count > 0 && avail > 0) {
            int bw = Math.Min((int)(190 * scale), avail / rest.Count);
            winSlot = bw;
            int pad = (int)(2 * scale), isz = (int)(20 * scale);
            List<int> word = new List<int>();
            for (int i = 0; i < rest.Count; i++) word.Add(i);
            bool winDrag = dragging && dragGroup == 1 && dragFrom >= 0 && dragFrom < rest.Count;
            if (winDrag) { word.RemoveAt(dragFrom); word.Insert(Math.Max(0, Math.Min(dragTo, word.Count)), dragFrom); }
            for (int k = 0; k < word.Count; k++) {
                int wi = word[k]; Win w = rest[wi];
                Rectangle r = new Rectangle(bx + k * bw, pad, bw - pad, H - 2 * pad);
                if (!(winDrag && wi == dragFrom)) DrawWinButton(g, w, r, false, isz, tf);
                Win cw = w;
                Hit wh = new Hit(); wh.R = r; wh.Key = "w:" + cw.H.ToInt64(); wh.Group = 1; wh.Slot = wi;
                wh.A = delegate(MouseButtons b) { WinClick(cw, b); }; hits.Add(wh);
            }
            if (winDrag) {
                int lx2 = Math.Max(bx, Math.Min(dragX - bw / 2, bx + (rest.Count - 1) * bw));
                DrawWinButton(g, rest[dragFrom], new Rectangle(lx2, pad, bw - pad, H - 2 * pad), true, isz, tf);
            }
        }
    }

    void DrawPinButton(Graphics g, string pp, Rectangle pr, bool lifted, int iz) {
        List<Win> pg = Group(pp);
        bool pact = false;
        foreach (Win pwn in pg) if (pwn.Active && !pwn.Min) pact = true;
        if (lifted || pact || hoverR == pr) using (SolidBrush pb = new SolidBrush((lifted || pact) ? ACT : HOV)) g.FillRectangle(pb, pr);
        Icon pic = FileIcon(pp);
        if (pic != null) { try { g.DrawIcon(pic, new Rectangle(pr.X + (pr.Width - iz) / 2, pr.Y + (pr.Height - iz) / 2, iz, iz)); } catch { } }
        else TextRenderer.DrawText(g, "?", font, pr, FG, TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.NoPadding);
        if (pg.Count > 0) {
            int ih = Math.Max(2, (int)(2 * scale)), iw = pact ? pr.Width / 2 : pr.Width / 4;
            using (SolidBrush ib = new SolidBrush(pact ? ACCENT : DIM)) g.FillRectangle(ib, pr.X + (pr.Width - iw) / 2, pr.Bottom - ih, iw, ih);
        }
    }

    void DrawWinButton(Graphics g, Win w, Rectangle r, bool lifted, int isz, TextFormatFlags tf) {
        bool act = w.Active && !w.Min;
        if (lifted || act || hoverR == r) using (SolidBrush bb = new SolidBrush((lifted || act) ? ACT : HOV)) g.FillRectangle(bb, r);
        int tx = r.X + (int)(6 * scale);
        if (w.Icon != IntPtr.Zero) {
            try { g.DrawIcon(Icon.FromHandle(w.Icon), new Rectangle(tx, r.Y + (r.Height - isz) / 2, isz, isz)); } catch { }
            tx += isz + (int)(6 * scale);
        }
        Rectangle tr = new Rectangle(tx, r.Y, Math.Max(0, r.Right - tx - (int)(4 * scale)), r.Height);
        if (tr.Width > 8) TextRenderer.DrawText(g, w.Title, font, tr, w.Min ? DIM : FG, tf);
        if (act) using (SolidBrush ab = new SolidBrush(ACCENT)) g.FillRectangle(ab, r.X + r.Width / 4, r.Bottom - Math.Max(2, (int)(2 * scale)), r.Width / 2, Math.Max(2, (int)(2 * scale)));
    }

    // ---------- drag to arrange ----------
    protected override void OnMouseDown(MouseEventArgs e) {
        dragGroup = -1; dragFrom = -1; dragging = false;
        trayOpenAtDown = trayShown || OverflowWindow() != IntPtr.Zero;
        if (e.Button == MouseButtons.Left) {
            foreach (Hit h in hits)
                if (h.R.Contains(e.Location)) {
                    if (h.Group >= 0) { dragGroup = h.Group; dragFrom = h.Slot; dragTo = h.Slot; downPt = e.Location; dragX = e.X; }
                    break;
                }
        }
        base.OnMouseDown(e);
    }

    // moves one open-window button to a new slot by rewriting the stable order list
    void CommitWinMove(int from, int to) {
        List<long> was = new List<long>();
        foreach (Win w in restWins) was.Add(w.H.ToInt64());
        if (from < 0 || from >= was.Count) return;
        List<long> now = new List<long>(was);
        long moved = now[from]; now.RemoveAt(from); now.Insert(Math.Max(0, Math.Min(to, now.Count)), moved);
        int j = 0;
        for (int i = 0; i < order.Count && j < now.Count; i++)
            if (was.Contains(order[i])) order[i] = now[j++];
    }

    protected override void OnMouseMove(MouseEventArgs e) {
        if (dragFrom >= 0 && (e.Button & MouseButtons.Left) != 0) {
            if (!dragging && Math.Abs(e.X - downPt.X) > (int)(5 * scale)) { dragging = true; HidePreview(); }
            if (dragging) {
                dragX = e.X;
                int x0 = dragGroup == 0 ? pinX0 : winX0, slotW = dragGroup == 0 ? pinSlot : winSlot;
                int count = dragGroup == 0 ? pins.Count : restWins.Count;
                int slot = slotW > 0 ? (e.X - x0) / slotW : dragFrom;
                dragTo = Math.Max(0, Math.Min(count - 1, slot));
                Invalidate();
                return;
            }
        }
        Rectangle nr = Rectangle.Empty;
        foreach (Hit h in hits) if (h.R.Contains(e.Location)) { nr = h.R; break; }
        if (nr != hoverR) { hoverR = nr; Invalidate(); }
        base.OnMouseMove(e);
    }
    protected override void OnMouseLeave(EventArgs e) { hoverR = Rectangle.Empty; Invalidate(); base.OnMouseLeave(e); }
    protected override void OnMouseUp(MouseEventArgs e) {
        HidePreview();
        ClosePop();
        if (dragging) {   // finished dragging: apply the new order, and don't treat it as a click
            dragging = false;
            if (dragGroup == 0 && dragFrom >= 0 && dragFrom < pins.Count && dragTo != dragFrom) {
                string moved = pins[dragFrom]; pins.RemoveAt(dragFrom); pins.Insert(Math.Min(dragTo, pins.Count), moved); SavePins();
            }
            else if (dragGroup == 1 && dragTo != dragFrom) { CommitWinMove(dragFrom, dragTo); Tick(); }
            dragGroup = -1; dragFrom = -1;
            Invalidate();
            return;
        }
        dragGroup = -1; dragFrom = -1;
        bool onItem = false;
        foreach (Hit h in hits) if (h.R.Contains(e.Location)) { onItem = true; h.A(e.Button); break; }
        if (!onItem && e.Button == MouseButtons.Right) ShowBarMenu();
        base.OnMouseUp(e);
    }

    [STAThread]
    static void Main() {
        bool created;
        Mutex mx = new Mutex(true, "FableThinBarSingleInstance", out created);
        if (!created) return;
        Log.Write("Fable Thin Bar starting");
        AppDomain.CurrentDomain.UnhandledException += delegate(object s, UnhandledExceptionEventArgs e) { Log.Write("CRASH: " + e.ExceptionObject); };
        Application.SetUnhandledExceptionMode(UnhandledExceptionMode.CatchException);
        Application.ThreadException += delegate(object s, System.Threading.ThreadExceptionEventArgs e) { Log.Write("ERROR: " + e.Exception); };
        // At login this can start before the desktop is ready: wait (up to 60 s) for the real taskbar window to exist.
        for (int i = 0; i < 120 && Native.FindWindow("Shell_TrayWnd", null) == IntPtr.Zero; i++) Thread.Sleep(500);
        Native.SetProcessDPIAware();
        Application.EnableVisualStyles();
        Application.Run(new Bar());
        GC.KeepAlive(mx);
    }
