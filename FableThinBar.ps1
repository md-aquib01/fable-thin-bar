    Bitmap CaptureWin(IntPtr h) {
        RECT r; if (!Native.GetWindowRect(h, out r)) return null;
        int w = r.Right - r.Left, ht = r.Bottom - r.Top;
        if (w <= 0 || ht <= 0) return null;
        double k = Math.Min((double)snapW / w, (double)snapH / ht);
        if (k > 1.0) k = 1.0;
        int tw = Math.Max(1, (int)(w * k)), th = Math.Max(1, (int)(ht * k));
        using (Bitmap full = new Bitmap(w, ht, PixelFormat.Format24bppRgb)) {
            using (Graphics fg = Graphics.FromImage(full)) {
                IntPtr dc = fg.GetHdc();
                bool ok = Native.PrintWindow(h, dc, 2);   // 2 = PW_RENDERFULLCONTENT
                fg.ReleaseHdc(dc);
                if (!ok) return null;
            }
            Bitmap small = new Bitmap(tw, th, PixelFormat.Format24bppRgb);
            using (Graphics sg = Graphics.FromImage(small)) {
                sg.InterpolationMode = InterpolationMode.HighQualityBilinear;
                sg.DrawImage(full, 0, 0, tw, th);
            }
            return small;
        }
    }

