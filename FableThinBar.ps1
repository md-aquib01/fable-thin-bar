static class TrayChevron {
    public static bool Looks(string name, string id, string cls) {
        name = (name ?? "").ToLowerInvariant(); id = (id ?? "").ToLowerInvariant(); cls = (cls ?? "").ToLowerInvariant();
        if (name.Contains("hidden icon") || name.Contains("notification chevron")) return true;   // English Windows 11 / Windows 10
        if (id.Contains("chevron") || cls.Contains("chevron")) return true;
        return false;
    }
    public static bool Press(IUIAElement el) {
        object o;
        try { o = el.GetCurrentPattern(10000); IUIAInvoke iv = o as IUIAInvoke; if (iv != null) { iv.Invoke(); return true; } } catch { }
        try { o = el.GetCurrentPattern(10015); IUIAToggle tg = o as IUIAToggle; if (tg != null) { tg.Toggle(); return true; } } catch { }
        try { o = el.GetCurrentPattern(10005); IUIAExpand ex = o as IUIAExpand; if (ex != null) { ex.Expand(); return true; } } catch { }
        return false;
    }
    static KINPUT K(ushort vk, bool up) { KINPUT k = new KINPUT(); k.Type = 1; k.Vk = vk; k.Flags = up ? 2u : 0u; return k; }
    public static void Keys(params ushort[] downUp) {   // presses all keys down in order, then releases them in reverse
        KINPUT[] a = new KINPUT[downUp.Length * 2];
        for (int i = 0; i < downUp.Length; i++) { a[i] = K(downUp[i], false); a[a.Length - 1 - i] = K(downUp[i], true); }
        Native.SendInput((uint)a.Length, a, Marshal.SizeOf(typeof(KINPUT)));
    }
    static string Describe(IUIAElement el) {
        string name = "", id = "", cls = "";
        try { name = el.get_CurrentName(); } catch { }
        try { id = el.get_CurrentAutomationId(); } catch { }
        try { cls = el.get_CurrentClassName(); } catch { }
        return name + " | " + id + " | " + cls;
    }
    // Win+B moves keyboard focus into the tray. Only when focus really is on the "Show hidden icons" button do we press it;
    // otherwise we press Esc, so a different tray icon or Start can never open by mistake.
    static IUIA uiaCached;
    public static bool ViaFocus() {
        try {
            if (uiaCached == null) uiaCached = (IUIA)new CUIAutomation();
            string last = "";
            for (int attempt = 0; attempt < 2; attempt++) {
                Keys(0x5B, 0x42);   // Win+B, sent as one batch
                for (int t = 0; t < 12; t++) {
                    Thread.Sleep(25);
                    IUIAElement f = null;
                    try { f = uiaCached.GetFocusedElement(); } catch { }
                    if (f == null) continue;
                    string name = "", id = "", cls = "";
                    try { name = f.get_CurrentName(); } catch { }
                    try { id = f.get_CurrentAutomationId(); } catch { }
                    try { cls = f.get_CurrentClassName(); } catch { }
                    if (Looks(name, id, cls)) {
                        if (!Press(f)) Keys(0x20);   // Space
                        return true;
                    }
                    string now = name + " | " + id + " | " + cls;
                    if (now != last) { last = now; if (t >= 3) break; }   // focus settled somewhere else: try Win+B again
                }
            }
            Keys(0x1B);   // Esc: leave the tray without opening anything
            Log.Write("tray: Win+B focused [" + last + "], not the hidden-icons button");
        } catch (Exception ex) { Log.Write("tray focus: " + ex.Message); uiaCached = null; }
        return false;
    }
    public static void LogShell(IntPtr tray) {
        try {
            string build = "";
            try { build = Microsoft.Win32.Registry.GetValue(@"HKEY_LOCAL_MACHINE\SOFTWARE\Microsoft\Windows NT\CurrentVersion", "CurrentBuild", "") as string; } catch { }
            StringBuilder sb = new StringBuilder();
            Native.EnumChildWindows(tray, delegate(IntPtr h, IntPtr l) {
                StringBuilder c = new StringBuilder(128); Native.GetClassName(h, c, 128);
                RECT r; Native.GetWindowRect(h, out r);
                if (sb.Length < 3000) sb.Append("[").Append(c).Append(Native.IsWindowVisible(h) ? " vis " : " hid ").Append(r.Left).Append(",").Append(r.Top).Append(" ").Append(r.Right - r.Left).Append("x").Append(r.Bottom - r.Top).Append("] ");
                return true;
            }, IntPtr.Zero);
            Log.Write("tray diag: build " + build + "; taskbar windows: " + sb);
        } catch { }
    }

    // Returns true when the button was found and pressed.
    public static bool Press(IntPtr tray) {
        if (tray == IntPtr.Zero) return false;
        IUIA uia = null;
        try {
            uia = (IUIA)new CUIAutomation();
            IUIAElement root = uia.ElementFromHandle(tray);
            IUIAArray all = root.FindAll(4, uia.CreateTrueCondition());   // TreeScope.Descendants
            int n = all.get_Length();
            StringBuilder seen = new StringBuilder();
            for (int i = 0; i < n; i++) {
                IUIAElement el = all.GetElement(i);
                string name = "", id = "", cls = "";
                try { name = el.get_CurrentName(); } catch { }
                try { id = el.get_CurrentAutomationId(); } catch { }
                try { cls = el.get_CurrentClassName(); } catch { }
                if (seen.Length < 4000) seen.Append("[").Append(name).Append(" | ").Append(id).Append(" | ").Append(cls).Append("] ");
                if (Looks(name, id, cls) && Press(el)) return true;
            }
            Log.Write("tray button not found (" + n + " items). Items seen: " + seen);
        } catch (Exception ex) { Log.Write("tray press: " + ex.Message); }
        finally { if (uia != null) try { Marshal.ReleaseComObject(uia); } catch { } }
        return false;
    }
}

