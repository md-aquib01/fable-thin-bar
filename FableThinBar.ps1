    void TrayClick(MouseButtons b) {
        if (b != MouseButtons.Left) return;
        // Popup was open: the press itself closed it (or Esc closes it now). Don't open it again.
        if (trayOpenAtDown) {
            trayOpenAtDown = false;
            if (OverflowWindow() != IntPtr.Zero) TrayChevron.Keys(0x1B);
            trayShown = false; Invalidate();
            return;
        }
        if (trayBusy) return;
        trayBusy = true;
        // Bring the real taskbar back invisibly (transparent + click-through) so its popup has something to anchor to.
        hideSuspendUntil = DateTime.UtcNow.AddSeconds(2);
        trayOpen = true;
        GhostTaskbar(true);
        SetNativeTaskbar(true);
        IntPtr tray = Native.FindWindow("Shell_TrayWnd", null);
        bool logIt = !trayLogged; trayLogged = true;
        bool win11 = WinBuild() >= 22000;
        Thread th = new Thread(delegate() {
            Thread.Sleep(40);
            if (logIt) TrayChevron.LogShell(tray);
            bool ok = false;
            if (!win11) {
                // Windows 10: the classic arrow is a real button inside the tray area
                IntPtr notify = Native.FindWindowEx(tray, IntPtr.Zero, "TrayNotifyWnd", null);
                IntPtr btn = notify != IntPtr.Zero ? Native.FindWindowEx(notify, IntPtr.Zero, "Button", null) : IntPtr.Zero;
                if (btn != IntPtr.Zero && Native.IsWindowVisible(btn)) { Native.PostMessage(btn, 0xF5, IntPtr.Zero, IntPtr.Zero); ok = true; }
                if (!ok) ok = TrayChevron.Press(tray);
            }
            // Windows 11 (and fallback): Win+B, but only press when focus is really on "Show hidden icons"
            if (!ok) ok = TrayChevron.ViaFocus();
            try {
                BeginInvoke(new Action(delegate {
                    trayBusy = false;
                    if (!ok) { trayOpen = false; hideSuspendUntil = DateTime.MinValue; }   // nothing opened: hide the real taskbar again
                }));
            } catch { trayBusy = false; }
            if (ok) {   // move the popup above our arrow the moment it appears
                for (int t = 0; t < 40; t++) {
                    IntPtr ov = OverflowWindow();
                    if (ov != IntPtr.Zero) {
                        try { Invoke(new Action(delegate { PlaceOverflow(ov); trayShown = true; Invalidate(); })); } catch { }
                        if (t > 10) break;
                    }
                    Thread.Sleep(15);
                }
            }
        });
        th.SetApartmentState(ApartmentState.MTA);
        th.IsBackground = true;
        th.Start();
    }
