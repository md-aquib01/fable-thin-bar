# Fable Thin Bar - a thin, minimal taskbar for Windows 11 / 10.
# One script, no third-party software: it compiles a small app with the C# compiler that ships with Windows.
#
#   powershell -ExecutionPolicy Bypass -File .\FableThinBar.ps1               # install + start
#   powershell -ExecutionPolicy Bypass -File .\FableThinBar.ps1 -NativeOnly   # just shrink the built-in taskbar
#   powershell -ExecutionPolicy Bypass -File .\FableThinBar.ps1 -Uninstall    # revert everything
#
# Licence: MIT. Not affiliated with Microsoft.
param([switch]$Uninstall, [switch]$NativeOnly)

$app    = "FableThinBar"
$dir    = Join-Path $env:LOCALAPPDATA $app
$src    = Join-Path $dir "$app.cs"
$exe    = Join-Path $dir "$app.exe"
$ico    = Join-Path $dir "$app.ico"
$oldDir = Join-Path $env:LOCALAPPDATA "ThinBar"     # earlier, unnamed builds lived here
$runKey = "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Run"
$sr     = "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Explorer\StuckRects3"
$adv    = "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Explorer\Advanced"

function Set-AutoHide([bool]$on) {
    $v = (Get-ItemProperty -Path $sr).Settings
    $v[8] = $(if ($on) { 3 } else { 2 })
    Set-ItemProperty -Path $sr -Name Settings -Value $v
}

if ($Uninstall) {
    Stop-Process -Name $app, ThinBar -Force -ErrorAction SilentlyContinue
    Remove-ItemProperty -Path $runKey -Name $app, ThinBar -ErrorAction SilentlyContinue
    Remove-Item (Join-Path ([Environment]::GetFolderPath('Startup')) 'Fable Thin Bar.lnk'), (Join-Path ([Environment]::GetFolderPath('Startup')) 'ThinBar.lnk') -Force -ErrorAction SilentlyContinue
    Set-AutoHide $false
    Set-ItemProperty -Path $adv -Name TaskbarSi -Value 1 -Type DWord -ErrorAction SilentlyContinue
    Stop-Process -Name explorer -Force
    Remove-Item $dir -Recurse -Force -ErrorAction SilentlyContinue
    Write-Host "Fable Thin Bar removed. Your normal taskbar is back."
    return
}

if ($NativeOnly) {
    # Smallest the built-in taskbar goes (roughly 32px on Windows 11 - not as thin as 28px).
    Set-ItemProperty -Path $adv -Name TaskbarSi -Value 0 -Type DWord               # small icons
    Set-ItemProperty -Path $adv -Name ShowTaskViewButton -Value 0 -Type DWord      # hide Task View
    Set-ItemProperty -Path $adv -Name TaskbarAl -Value 0 -Type DWord               # left-align
    Set-ItemProperty -Path "HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Search" -Name SearchboxTaskbarMode -Value 0 -Type DWord
    try { Set-ItemProperty -Path $adv -Name TaskbarDa -Value 0 -Type DWord -ErrorAction Stop } catch {}  # widgets (may be locked on newer builds)
    Stop-Process -Name explorer -Force
    Write-Host "Done. Re-run with -Uninstall to revert."
    return
}

