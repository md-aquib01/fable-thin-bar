    // ---------- drag and drop (like the real taskbar) ----------
    //  - drop files on the bin icon        -> Recycle Bin
    //  - drop files on an app icon/button  -> open them with that app
    //  - hold dragged files over a window  -> that window comes to the front
    //  - drop a program or shortcut (.exe/.lnk) on the bar -> pin it
    void DragStateFrom(DragEventArgs e) {
        dragFiles = null; dragPinnable = false;
        if (!e.Data.GetDataPresent(DataFormats.FileDrop)) return;
        dragFiles = e.Data.GetData(DataFormats.FileDrop) as string[];
        if (dragFiles == null || dragFiles.Length == 0) { dragFiles = null; return; }
        dragPinnable = true;
        foreach (string f in dragFiles) {
            string ext = Path.GetExtension(f).ToLowerInvariant();
            if (ext != ".exe" && ext != ".lnk") dragPinnable = false;
        }
    }
    void ResetDrag() {
        dragFiles = null; dragPinnable = false; dragHoverKey = null; dragHoverDone = false;
        if (hoverR != Rectangle.Empty) { hoverR = Rectangle.Empty; Invalidate(); }
    }
    Hit HitAtClient(Point c) { foreach (Hit x in hits) if (x.R.Contains(c)) return x; return null; }
    static bool IsExplorer(string exe) { return exe.EndsWith("explorer.exe", StringComparison.OrdinalIgnoreCase); }
    // the program a pinned icon or a window button stands for
    string ExeForKey(string key) {
        if (key == null) return "";
        if (key.StartsWith("p:")) {
            string lower = key.Substring(2);
            foreach (string pp in pins) if (pp.ToLowerInvariant() == lower) return pp;
            return "";
        }
        if (key.StartsWith("w:")) { List<Win> ws = WinsFor(key); if (ws.Count > 0) return ws[0].Exe; }
        return "";
    }
    static void OpenWith(string exe, string[] files) {
        try {
            StringBuilder a = new StringBuilder();
            foreach (string f in files) { if (a.Length > 0) a.Append(' '); a.Append('"').Append(f.TrimEnd('\\')).Append('"'); }
            ProcessStartInfo psi = new ProcessStartInfo(exe, a.ToString());
            psi.UseShellExecute = true;
            Process.Start(psi);
        } catch { }
    }
    void PinDropped(string[] files, int x) {
        int idx = pins.Count;
        if (pinSlot > 0 && x >= pinX0 && x < pinX0 + pins.Count * pinSlot) idx = Math.Max(0, Math.Min(pins.Count, (x - pinX0) / pinSlot));
        foreach (string f in files) {
            string exe = f.EndsWith(".lnk", StringComparison.OrdinalIgnoreCase) ? ResolveLink(f) : f;
            if (exe.Length == 0 || IsPinned(exe)) continue;
            pins.Insert(Math.Min(idx, pins.Count), exe); idx++;
        }
        SavePins(); Invalidate();
    }

    void DragCheck(DragEventArgs e) {
        Hit h = HitAtClient(PointToClient(new Point(e.X, e.Y)));
        DragDropEffects eff = DragDropEffects.None;
        Rectangle hl = Rectangle.Empty;
        string hoverKey = null;
        if (dragFiles != null) {
            if (h != null && h.R == binR) { eff = DragDropEffects.Move; hl = binR; }
            else if (dragPinnable) eff = DragDropEffects.Link;
            else if (h != null && h.Key != null) {
                string exe = ExeForKey(h.Key);
                if (exe.Length > 0 && !IsExplorer(exe)) { eff = DragDropEffects.Copy; hl = h.R; }
                if (WinsFor(h.Key).Count > 0) hoverKey = h.Key;
            }
        }
        e.Effect = eff;
        if (hl != hoverR) { hoverR = hl; Invalidate(); }
        if (hoverKey != dragHoverKey) { dragHoverKey = hoverKey; dragHoverSince = Environment.TickCount; dragHoverDone = false; }
        else if (hoverKey != null && !dragHoverDone && Environment.TickCount - dragHoverSince >= 700) {
            dragHoverDone = true;   // held over a window for a moment: bring it forward so the files can be dropped into it
            List<Win> ws = WinsFor(hoverKey);
            if (ws.Count > 0) Activate(ws[0]);
        }
    }
    protected override void OnDragEnter(DragEventArgs e) { DragStateFrom(e); DragCheck(e); base.OnDragEnter(e); }
    protected override void OnDragOver(DragEventArgs e) { DragCheck(e); base.OnDragOver(e); }
    protected override void OnDragLeave(EventArgs e) { ResetDrag(); base.OnDragLeave(e); }
    protected override void OnDragDrop(DragEventArgs e) {
        Point c = PointToClient(new Point(e.X, e.Y));
        Hit h = HitAtClient(c);
        string[] files = dragFiles; bool pinnable = dragPinnable;
        ResetDrag();
        if (files != null && files.Length > 0) {
            if (h != null && h.R == binR) RecycleFiles(files);
            else if (pinnable) PinDropped(files, c.X);
            else if (h != null && h.Key != null) {
                string exe = ExeForKey(h.Key);
                if (exe.Length > 0 && !IsExplorer(exe)) OpenWith(exe, files);
            }
        }
        base.OnDragDrop(e);
    }
