    void LoadNotes() {
        try {
            if (!File.Exists(notesFile)) return;
            List<NoteData> list = new List<NoteData>();
            NoteData cur = null;
            foreach (string line in File.ReadAllLines(notesFile)) {
                string[] p = line.Split('|');
                if (p[0] == "N" && p.Length >= 8) {
                    cur = new NoteData();
                    int.TryParse(p[1], out cur.X); int.TryParse(p[2], out cur.Y); int.TryParse(p[3], out cur.Tint);
                    cur.Top = p[4] == "1"; cur.Visible = p[5] == "1";
                    int.TryParse(p[6], out cur.Seed);
                    cur.Title = UnB64(p[7]); if (cur.Title.Length == 0) cur.Title = "Today";
                    list.Add(cur);
                }
                else if (p[0] == "T" && p.Length >= 4 && cur != null) {
                    TaskItem t = new TaskItem();
                    int.TryParse(p[1], out t.Level); t.Done = p[2] == "1"; t.Text = UnB64(p[3]); t.Plain = p.Length >= 5 && p[4] == "1";
                    cur.Tasks.Add(t);
                }
            }
            foreach (NoteData d in list) AddNote(d);
        } catch (Exception ex) { Log.Write("notes load: " + ex); }
    }
