    static string ResolveLink(string lnk) {
        object sh = null, sc = null;
        try {
            Type t = Type.GetTypeFromProgID("WScript.Shell");
            if (t == null) return "";
            sh = Activator.CreateInstance(t);
            sc = t.InvokeMember("CreateShortcut", System.Reflection.BindingFlags.InvokeMethod, null, sh, new object[] { lnk });
            Type st = sc.GetType();
            string target = st.InvokeMember("TargetPath", System.Reflection.BindingFlags.GetProperty, null, sc, null) as string;
            string args = st.InvokeMember("Arguments", System.Reflection.BindingFlags.GetProperty, null, sc, null) as string;
            if (string.IsNullOrEmpty(target)) return "";
            target = Environment.ExpandEnvironmentVariables(target);
            if (!target.EndsWith(".exe", StringComparison.OrdinalIgnoreCase)) return "";
            if (args != null && (args.IndexOf("shell:", StringComparison.OrdinalIgnoreCase) >= 0 || args.IndexOf("AppsFolder", StringComparison.OrdinalIgnoreCase) >= 0)) return "";   // Store apps
            return File.Exists(target) ? target : "";
        } catch { return ""; }
        finally {
            if (sc != null) Marshal.ReleaseComObject(sc);
            if (sh != null) Marshal.ReleaseComObject(sh);
        }
    }
    void SyncNativePins() {
        try {
            if (!Directory.Exists(nativeDir)) return;
            Dictionary<string, bool> present = new Dictionary<string, bool>(StringComparer.OrdinalIgnoreCase);
            bool changed = false;
            foreach (string f in Directory.GetFiles(nativeDir, "*.lnk")) {
                string name = Path.GetFileName(f);
                present[name] = true;
                nativeMissing.Remove(name);
                if (nativeMap.ContainsKey(name)) continue;
                string exe = ResolveLink(f);
                nativeMap[name] = exe; changed = true;
                if (exe.Length > 0) Pin(exe);
            }
            List<string> gone = new List<string>();
            foreach (string k in nativeMap.Keys) {
                if (present.ContainsKey(k)) continue;
                int n; nativeMissing.TryGetValue(k, out n); n++;
                nativeMissing[k] = n;
                if (n >= 2) gone.Add(k);   // missing on two scans in a row, so it really was unpinned
            }
            foreach (string k in gone) {
                string exe = nativeMap[k];
                nativeMap.Remove(k); nativeMissing.Remove(k); changed = true;
                if (exe.Length > 0) Unpin(exe);
            }
            if (changed) SaveNative();
        } catch { }
    }

