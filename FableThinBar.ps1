        IntPtr fg = Native.GetForegroundWindow(), self = Handle;
        Native.EnumWindows(delegate(IntPtr h, IntPtr l) {
            if (h == self || !Native.IsWindowVisible(h)) return true;
            int len = Native.GetWindowTextLength(h);
            if (len == 0) return true;
            int ex = Native.GetWindowLong(h, -20);
            bool tool = (ex & 0x80) != 0, app = (ex & 0x40000) != 0;
            if (tool && !app) return true;
            if (Native.GetWindow(h, 4) != IntPtr.Zero && !app) return true;
            int cloaked; Native.DwmGetWindowAttribute(h, 14, out cloaked, 4);
            if (cloaked != 0) return true;
            csb.Length = 0; Native.GetClassName(h, csb, 64);
            string c = csb.ToString();
            if (c == "Progman" || c == "WorkerW" || c == "Shell_TrayWnd") return true;
            if (tsb.Capacity < len + 1) tsb.Capacity = len + 1;
            tsb.Length = 0; Native.GetWindowText(h, tsb, tsb.Capacity);
            long hid = h.ToInt64();
            string exe2;
            if (!exeCache.TryGetValue(hid, out exe2)) {   // a window's program never changes, so look it up once
                exe2 = ExePath(h);
                if (exe2.EndsWith("ApplicationFrameHost.exe", StringComparison.OrdinalIgnoreCase)) exe2 = "";  // Store apps can't be pinned
                exeCache[hid] = exe2;
            }
            IntPtr ic2;
            if (!iconCache.TryGetValue(hid, out ic2) || ic2 == IntPtr.Zero) { ic2 = GetIcon(h); iconCache[hid] = ic2; }
            Win w = new Win();
            w.H = h; w.Title = tsb.ToString(); w.Icon = ic2; w.Active = (h == fg); w.Min = Native.IsIconic(h);
            w.Exe = exe2;
            list.Add(w);
            return true;
        }, IntPtr.Zero);

        // Keep buttons in a stable order (first seen stays first) instead of z-order, which jumps around.
        List<Win> sorted = new List<Win>();
        List<long> newOrder = new List<long>();
        foreach (long oid in order)
            foreach (Win q in list)
                if (q.H.ToInt64() == oid) { sorted.Add(q); newOrder.Add(oid); }
        foreach (Win q2 in list) {
            long qid = q2.H.ToInt64();
            if (!newOrder.Contains(qid)) { sorted.Add(q2); newOrder.Add(qid); }
        }
        order = newOrder;
        PurgeGone(newOrder);
        return sorted;
    }

    void PurgeGone(List<long> alive) {
        List<long> dead = new List<long>();
        foreach (long k in snaps.Keys) if (!alive.Contains(k)) dead.Add(k);
        foreach (long k in dead) { Bitmap b = snaps[k]; if (b != null) b.Dispose(); snaps.Remove(k); }
        dead.Clear();
        foreach (long k in exeCache.Keys) if (!alive.Contains(k)) dead.Add(k);
        foreach (long k in dead) exeCache.Remove(k);
        dead.Clear();
        foreach (long k in iconCache.Keys) if (!alive.Contains(k)) dead.Add(k);
        foreach (long k in dead) iconCache.Remove(k);
    }

