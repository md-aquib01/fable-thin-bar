            }
        } else if (inPrev) {
            leaving = false; pendKey = previewKey;
        } else {
            pendKey = null;
            if (previewKey != null) {
                if (!leaving) { leaving = true; leaveSince = Environment.TickCount; }
                else if (Environment.TickCount - leaveSince > 250) HidePreview();
            }
        }
    }
