    static string ExePath(IntPtr hwnd) {
        uint pid; Native.GetWindowThreadProcessId(hwnd, out pid);
        if (pid == 0) return "";
        IntPtr ph = Native.OpenProcess(0x1000, false, pid);   // PROCESS_QUERY_LIMITED_INFORMATION
        if (ph == IntPtr.Zero) return "";
        try {
            StringBuilder sb = new StringBuilder(1024); int n = sb.Capacity;
            if (Native.QueryFullProcessImageName(ph, 0, sb, ref n)) return sb.ToString();
        } finally { Native.CloseHandle(ph); }
        return "";
    }

