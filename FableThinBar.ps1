    void BeginEdit(int kind, int index) {
        CommitEdit();
        edKind = kind; edIndex = index;
        string txt;
        if (kind == 3) { txt = D.Title; ed.MaxLength = 40; }
        else if (kind == 1 && index >= 0 && index < D.Tasks.Count) { txt = D.Tasks[index].Text; ed.MaxLength = 0; }
        else { edKind = 2; edIndex = -1; txt = ""; ed.MaxLength = 0; }
        ed.Text = txt.Replace("\n", "\r\n");
        editLines = 1;
        PlaceEditor();
        ed.Focus();
        ed.SelectionStart = ed.TextLength;
        Invalidate();
    }

    void PlaceEditor() {
        if (edKind == 0) return;
        int ci = D.Tint % PA.Length;
        int vis = Math.Max(1, (rowsBottom - rowsTop) / RH);
        Rectangle r;
        if (edKind == 3) {
            r = titleR; if (ed.Font != fTitle) ed.Font = fTitle;
            ed.Width = r.Width; ed.Height = r.Height;
            ed.Location = new Point(r.X, r.Y);
            ed.Visible = true;
            editLines = 1;
        } else {
            int lvl = (edKind == 1 && edIndex >= 0 && edIndex < D.Tasks.Count) ? D.Tasks[edIndex].Level : newLevel;
            int tx = textX + lvl * indentPx;
            if (ed.Font != fText) ed.Font = fText;
            ed.Width = (int)(ColsFor(tx) * cw + cw * 0.4f);
            ed.Visible = true;
            editLines = EditorLines();
            LayoutBody();
            int start = (edKind == 1 && edIndex < blks.Count) ? blks[edIndex].Start : addStart;
            if (start + editLines > scroll + vis) scroll = start + editLines - vis;
            if (start < scroll) scroll = start;
            ClampScroll(vis);
            ed.Height = editLines * RH;
            r = new Rectangle(tx, rowsTop + (start - scroll) * RH, ed.Width, ed.Height);
            ed.Location = new Point(r.X, r.Y);
        }
        ed.BackColor = Lerp(PA[ci], PB[ci], (r.Y + r.Height / 2f - PTop) / (float)(Hn - PTop));
        ed.ForeColor = INK;
    }

    void CommitEdit() {
        if (edKind == 0) return;
        int k = edKind, idx = edIndex;
        string t = ed.Text.Replace("\r\n", "\n").Trim();
        edKind = 0; edIndex = -1;
        ed.Visible = false;
        editLines = 1;
        if (k == 3) D.Title = t.Length > 0 ? t.Replace("\n", " ") : "Today";
        else if (k == 1) {
            if (idx >= 0 && idx < D.Tasks.Count) { if (t.Length == 0) D.Tasks.RemoveAt(idx); else D.Tasks[idx].Text = t; }
        }
        else if (k == 2 && t.Length > 0) {
            TaskItem ti = new TaskItem(); ti.Text = t; ti.Plain = newPlain; ti.Level = D.Tasks.Count > 0 ? newLevel : 0;
            D.Tasks.Add(ti);
            scroll = 1000000;   // jump to the bottom (clamped when painting)
        }
        changed();
        Invalidate();
    }

    void EdKey(object sender, KeyEventArgs e) {
        if (e.KeyCode == Keys.Enter) {
            e.SuppressKeyPress = true;
            if (e.Shift && edKind != 3) { ed.SelectedText = "\r\n"; return; }   // Shift+Enter = new line inside the same item
            bool again = edKind == 2 && ed.Text.Trim().Length > 0;
            CommitEdit();
            if (again) BeginEdit(2, -1);
        }
        else if (e.KeyCode == Keys.Escape) {
            e.SuppressKeyPress = true;
            edKind = 0; edIndex = -1; ed.Visible = false; editLines = 1; Invalidate();
        }
        else if (e.KeyCode == Keys.Tab && edKind != 3) {
            e.SuppressKeyPress = true;
            bool can = (edKind == 1 && edIndex > 0) || (edKind == 2 && D.Tasks.Count > 0);
            int nl = e.Shift ? 0 : (can ? 1 : 0);
            if (edKind == 1) D.Tasks[edIndex].Level = nl; else newLevel = nl;
            changed(); PlaceEditor(); Invalidate();
        }
    }

