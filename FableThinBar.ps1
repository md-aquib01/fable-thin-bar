    public void Present(List<Win> ws, Rectangle anchor, int barTop) {
        ClearThumbs();
        Rectangle scr = Screen.PrimaryScreen.Bounds;
        int maxN = Math.Max(1, (scr.Width - 2 * pad) / (cw + gap));
        items = (ws.Count > maxN) ? ws.GetRange(0, maxN) : ws;
        int n = items.Count;
        int ch = titleH + th + foot;
        int W = 2 * pad + n * cw + (n - 1) * gap, H = 2 * pad + ch;
        cards.Clear();
        for (int i = 0; i < n; i++) cards.Add(new Rectangle(pad + i * (cw + gap), pad, cw, ch));
        int x = anchor.Left + anchor.Width / 2 - W / 2;
        x = Math.Max(scr.Left + 4, Math.Min(x, scr.Right - W - 4));
        Bounds = new Rectangle(x, barTop - H - (int)(4 * sc), W, H);
        hoverCard = -1; hoverClose = false;
        Sig = Signature(ws);
        if (!Visible) Show();

        for (int i = 0; i < n; i++) {
            Win w = items[i];
            IntPtr t = IntPtr.Zero;
            if (!w.Min) { if (Native.DwmRegisterThumbnail(Handle, w.H, out t) != 0) t = IntPtr.Zero; }
            thumbs.Add(t);
            if (t == IntPtr.Zero) continue;
            PSIZE sz; Native.DwmQueryThumbnailSourceSize(t, out sz);
            if (sz.W <= 0 || sz.H <= 0) continue;
            Rectangle area = ThumbArea(cards[i]);
            double k = Math.Min((double)area.Width / sz.W, (double)area.Height / sz.H);
            if (k > 1.0) k = 1.0;
            int dw = (int)(sz.W * k), dh = (int)(sz.H * k);
            DWMTP tp = new DWMTP();
            tp.Flags = 0x1 | 0x4 | 0x8;   // destination rect | opacity | visible
            tp.Opacity = 255; tp.Visible = true;
            tp.Dest.Left = area.X + (area.Width - dw) / 2;
            tp.Dest.Top = area.Y + (area.Height - dh) / 2;
            tp.Dest.Right = tp.Dest.Left + dw;
            tp.Dest.Bottom = tp.Dest.Top + dh;
            Native.DwmUpdateThumbnailProperties(t, ref tp);
        }
        Invalidate();
    }

    public static string Signature(List<Win> ws) {
        StringBuilder sb = new StringBuilder();
        foreach (Win w in ws) sb.Append(w.H).Append(w.Title).Append(w.Min ? 'M' : 'm').Append('|');
        return sb.ToString();
    }

    protected override void OnPaint(PaintEventArgs e) {
        Graphics g = e.Graphics;
        g.Clear(BG);
        using (Pen bp = new Pen(BORDER)) g.DrawRectangle(bp, 0, 0, ClientSize.Width - 1, ClientSize.Height - 1);
        TextFormatFlags tf = TextFormatFlags.NoPadding | TextFormatFlags.VerticalCenter | TextFormatFlags.Left | TextFormatFlags.EndEllipsis | TextFormatFlags.NoPrefix;
        int isz = (int)(16 * sc);
        for (int i = 0; i < cards.Count && i < items.Count; i++) {
            Rectangle c = cards[i]; Win w = items[i];
            g.SmoothingMode = SmoothingMode.AntiAlias;
            using (GraphicsPath cpath = Ui.Round(c, (int)(6 * sc))) using (SolidBrush b = new SolidBrush(i == hoverCard ? CARDH : CARD)) g.FillPath(b, cpath);
            g.SmoothingMode = SmoothingMode.Default;
            int tx = c.X + (int)(8 * sc);
            if (w.Icon != IntPtr.Zero) {
                try { g.DrawIcon(Icon.FromHandle(w.Icon), new Rectangle(tx, c.Y + (titleH - isz) / 2, isz, isz)); } catch { }
                tx += isz + (int)(6 * sc);
            }
            Rectangle cr = CloseRect(c);
            Rectangle tr = new Rectangle(tx, c.Y, Math.Max(0, cr.Left - tx - (int)(2 * sc)), titleH);
            if (tr.Width > 8) TextRenderer.DrawText(g, w.Title, font, tr, FG, tf);
            if (i == hoverCard) {
                if (hoverClose) {
                    g.SmoothingMode = SmoothingMode.AntiAlias;
                    using (GraphicsPath xpath = Ui.Round(cr, (int)(4 * sc))) using (SolidBrush xb = new SolidBrush(Color.FromArgb(196, 43, 28))) g.FillPath(xb, xpath);
                    g.SmoothingMode = SmoothingMode.Default;
                }
                TextRenderer.DrawText(g, "\uE711", icons, cr, FG, TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.NoPadding);
            }
            if (i < thumbs.Count && thumbs[i] == IntPtr.Zero) {
                // No live thumbnail (minimized): draw the last saved snapshot, or a big icon if there is none.
                Rectangle area = ThumbArea(c);
                Bitmap sn = getSnap(w);
                if (sn != null) {
                    double k = Math.Min((double)area.Width / sn.Width, (double)area.Height / sn.Height);
                    if (k > 1.0) k = 1.0;
                    int sw2 = (int)(sn.Width * k), sh2 = (int)(sn.Height * k);
                    g.DrawImage(sn, area.X + (area.Width - sw2) / 2, area.Y + (area.Height - sh2) / 2, sw2, sh2);
                    continue;
                }
                int big = (int)(32 * sc);
                if (w.Icon != IntPtr.Zero) {
                    try { g.DrawIcon(Icon.FromHandle(w.Icon), new Rectangle(area.X + (area.Width - big) / 2, area.Y + (area.Height - big) / 2 - (int)(8 * sc), big, big)); } catch { }
                }
                Rectangle lr = new Rectangle(area.X, area.Y + area.Height / 2 + (int)(14 * sc), area.Width, (int)(20 * sc));
                TextRenderer.DrawText(g, w.Min ? "Minimized" : "No preview", font, lr, DIM, TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.NoPadding);
            }
        }
    }

    protected override void OnMouseMove(MouseEventArgs e) {
        int hc = -1; bool hx = false;
        for (int i = 0; i < cards.Count; i++)
            if (cards[i].Contains(e.Location)) { hc = i; hx = CloseRect(cards[i]).Contains(e.Location); break; }
        if (hc != hoverCard || hx != hoverClose) { hoverCard = hc; hoverClose = hx; Invalidate(); }
        base.OnMouseMove(e);
    }
    protected override void OnMouseLeave(EventArgs e) { hoverCard = -1; hoverClose = false; Invalidate(); base.OnMouseLeave(e); }
    protected override void OnMouseUp(MouseEventArgs e) {
        for (int i = 0; i < cards.Count && i < items.Count; i++) {
            if (!cards[i].Contains(e.Location)) continue;
            Win w = items[i];
            if (e.Button == MouseButtons.Middle || (e.Button == MouseButtons.Left && CloseRect(cards[i]).Contains(e.Location)))
                Native.PostMessage(w.H, 0x10, IntPtr.Zero, IntPtr.Zero);   // close
            else if (e.Button == MouseButtons.Left) onPick(w);
            break;
        }
        base.OnMouseUp(e);
    }
}

