    void Tick() {
        tick++;
        if (tick % 33 == 0) iconCache.Clear();   // re-read window icons every ~10 s
        wins = GetWindows();

        snapTick++;
        Win need = null, act = null;
        foreach (Win sw in wins) {
            if (sw.Min) continue;
            if (sw.Active) act = sw;
            if (need == null && !snaps.ContainsKey(sw.H.ToInt64())) need = sw;
        }
        if (need != null) Snap(need);                             // first picture of a window
        else if (act != null && snapTick % 10 == 0) Snap(act);    // keep the active window's picture fresh (~every 3 s)

        if (tick % 3 == 0) {   // CPU, measured over ~1 s with the cheap kernel call (no PerformanceCounter)
            long ci, ck, cu;
            if (Native.GetSystemTimes(out ci, out ck, out cu)) {
                long tot = ck + cu;
                if (lastTot != 0 && tot > lastTot) cpuVal = Math.Max(0f, Math.Min(100f, 100f * ((tot - lastTot) - (ci - lastIdle)) / (tot - lastTot)));
                lastTot = tot; lastIdle = ci;
            }
        }
        MEMSTATUS ms = new MEMSTATUS(); ms.dwLength = (uint)Marshal.SizeOf(typeof(MEMSTATUS));
        Native.GlobalMemoryStatusEx(ref ms); ramVal = ms.dwMemoryLoad;
        PowerStatus ps = SystemInformation.PowerStatus;
        hasBat = (ps.BatteryChargeStatus & BatteryChargeStatus.NoSystemBattery) == 0;
        batPct = (int)Math.Round(ps.BatteryLifePercent * 100);
        charging = ps.PowerLineStatus == PowerLineStatus.Online;
        if (tick % 30 == 1) net = NetKind();
        if (tick % 30 == 2 || binStale) QueryBin();
        if (tick == 1 || tick % 10 == 3) SyncNativePins();   // about every 3 s
        if (notesDirty && DateTime.UtcNow >= notesSaveAt) { notesDirty = false; SaveNotes(); }

        sigSb.Length = 0;
        StringBuilder sb = sigSb;
        foreach (Win w in wins) sb.Append(w.H).Append(w.Title).Append(w.Active ? 'A' : 'a').Append(w.Min ? 'M' : 'm').Append(w.Icon).Append('|');
        sb.Append((int)cpuVal).Append('/').Append(ramVal).Append('/').Append(batPct).Append(charging).Append(net).Append(binItems > 0).Append(DateTime.Now.ToString("HHmm"));
        string s = sb.ToString();
        if (s != sig) { sig = s; Invalidate(); }

        if (previewKey != null) {
            List<Win> pw = WinsFor(previewKey);
            if (pw.Count == 0) HidePreview();
            else if (Preview.Signature(pw) != preview.Sig) preview.Present(pw, lastAnchor, Bounds.Top);
        }
    }

